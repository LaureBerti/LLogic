"""Reasoner validation of the Phase 1 filter.

The claim under test is the paper's deployment advice: that a practitioner may trust
an LLM-drafted definition once it has passed the Phase 1 satisfiability filter. The
the objection is that passing is nearly uninformative, because the checker sees
one definition in isolation while the surrounding ontology never constrains it. So the
question is:

    when the filter accepts a definition, does an OWL DL reasoner still accept it
    once that definition is asserted into an ontology that actually has constraints?

The quantity that decides whether the deployment claim survives is the FALSE-PASS
RATE: filter-accepted definitions that a reasoner finds unsatisfiable.

Three arms plus a control, differing only in what constrains the ontology:

  control  the study ontologies as they are. All seven declare zero disjointness, so
           this measures what the procedure yields when nothing can be contradicted.
           It is the null against which the other arms are read, and it is evidence
           for the sparse-constraint point rather than a result about models.
  arm_a    DBpedia with its own 27 asserted owl:disjointWith axioms. The only arm
           where an unsatisfiability verdict is licensed by the source ontology.
  arm_b    DBpedia plus the 170,144 pruned disjointness axioms released by Crum et al.
           (KBC-LM'24, arXiv 2410.03235). Those axioms are themselves LLM-generated by
           models of our size class, at a reported ~0.75 accuracy, so this arm measures
           consistency against a published enrichment, NOT correctness.
  arm_c    manual curation; the author's labels. Not computed here.

Arms A and B need definitions of DBpedia classes, which the study has not generated.
Until a Phase 1 run over DBpedia concepts exists they are reported as NOT RUN, with
the reason stated, rather than approximated by asserting anatomy definitions into
DBpedia --- classes that do not exist there would be created unconstrained and every
one would come back satisfiable, which would be an artefact and not a finding.

Translation fidelity is the main risk and is handled by refusing to guess: only the
conjunction-of-named-classes fragment is translated (see fol_to_owl.py), and the
not-translatable count is reported per cause instead of being hidden in a denominator.

Compute: CPU only, local. No LLM calls, no network. HermiT ships with owlready2.

Run:
    python src/analysis/reasoner_validation.py
    python src/analysis/reasoner_validation.py reasoner.arm=control reasoner.limit=200
"""

